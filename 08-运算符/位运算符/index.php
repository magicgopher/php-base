<?php
// 位运算符
// 对整数的二进制位进行运算

$a = 12; // 二进制：1100
$b = 10; // 二进制：1010

echo "$a & $b = " . ($a & $b) . '<br />';  // 1000，即 8
echo "$a | $b = " . ($a | $b) . '<br />';  // 1110，即 14
echo "$a ^ $b = " . ($a ^ $b) . '<br />';  // 0110，即 6
echo "~$a = " . (~$a) . '<br />';           // -13

// 左移一位相当于乘以 2，右移一位相当于除以 2
echo "$a << 1 = " . ($a << 1) . '<br />';  // 24
echo "$a >> 1 = " . ($a >> 1) . '<br />';  // 6
